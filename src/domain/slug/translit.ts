/**
 * Транслитерация кириллицы в латиницу для слагов.
 *
 * Правила бытовые, а не ГОСТ: цель — узнаваемый адрес, а не обратимость.
 * `х -> h`, `ц -> c`, `щ -> sch`, `ю -> yu`, `я -> ya`.
 * Твёрдый и мягкий знаки выкидываются.
 */
const MAP: Record<string, string> = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh', з: 'z',
  и: 'i', й: 'y', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r',
  с: 's', т: 't', у: 'u', ф: 'f', х: 'h', ц: 'c', ч: 'ch', ш: 'sh', щ: 'sch',
  ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya',

  // Украинский, белорусский, казахский — встречаются в именах.
  і: 'i', ї: 'yi', є: 'ye', ґ: 'g', ў: 'u', ә: 'a', ғ: 'g', қ: 'k', ң: 'n',
  ө: 'o', ұ: 'u', ү: 'u', һ: 'h',
};

/** Ожидает строку уже в нижнем регистре. */
export function transliterate(input: string): string {
  let result = '';
  for (const char of input) {
    const mapped = MAP[char];
    result += mapped === undefined ? char : mapped;
  }
  return result;
}
