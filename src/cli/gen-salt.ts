import { randomSecret } from '../util/random.js';

/**
 * Соль для суффиксов слагов миров.
 *
 * Генерируется один раз на инсталляцию и больше не меняется: уже выданные
 * слаги лежат в базе и от соли не зависят, но новый мир при потерянной соли
 * получит другой суффикс, чем получил бы раньше.
 */
process.stdout.write(
  [
    '# Соль для генерации суффиксов слагов миров.',
    '# Секрет: не коммитить. Генерируется ОДИН раз и не меняется — иначе',
    '# суффиксы новых миров перестанут совпадать с прежней схемой.',
    '',
    `SLUG_SALT=${randomSecret(32)}`,
    '',
  ].join('\n'),
);
