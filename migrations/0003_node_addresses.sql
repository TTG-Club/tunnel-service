-- Публичные IP-адреса ноды.
--
-- Приложение мастера искало ноду по имени через DNS пользователя. Кэш DNS у
-- провайдера или VPN держит старый адрес до часа (минимальный TTL deSEC), и
-- после смены IP ноды туннель у людей не поднимался. Нода сама сообщает свои
-- адреса в heartbeat, сервис отдаёт их в тикете, и приложение подключается
-- прямо по IP — имя ноды остаётся только для TLS (SNI и проверка сертификата).
--
-- Пустой массив — нода адресов не сообщила, клиент идёт через DNS, как раньше.

alter table nodes add column addresses text[] not null default '{}';
